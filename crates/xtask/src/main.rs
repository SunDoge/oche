use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

const SYMBOLS: &[&str] = &[
    "Dart_CurrentIsolate",
    "Dart_CurrentIsolateGroupId",
    "Dart_EnterScope",
    "Dart_ExitScope",
    "Dart_IsError",
    "Dart_GetError",
    "Dart_RootLibrary",
    "Dart_NewStringFromCString",
    "Dart_StringToCString",
    "Dart_NewInteger",
    "Dart_GetField",
    "Dart_Invoke",
    "Dart_InvokeClosure",
    "Dart_IntegerToInt64",
    "Dart_NewDouble",
    "Dart_DoubleValue",
    "Dart_NewBoolean",
    "Dart_BooleanValue",
    "Dart_NewExternalTypedDataWithFinalizer",
    "Dart_LoadLibrary",
    "Dart_LoadLibraryFromKernel",
    "Dart_FinalizeLoading",
];

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("xtask: {error}");
            ExitCode::FAILURE
        }
    }
}

fn run() -> Result<(), String> {
    let mut arguments = env::args().skip(1);
    if arguments.next().as_deref() != Some("dart-bindings") {
        return Err("usage: cargo run -p xtask -- dart-bindings --sdk <DART_SDK> [--check]".into());
    }
    let mut sdk = None;
    let mut check = false;
    while let Some(argument) = arguments.next() {
        match argument.as_str() {
            "--sdk" => sdk = arguments.next().map(PathBuf::from),
            "--check" => check = true,
            _ => return Err(format!("unknown argument '{argument}'")),
        }
    }
    let sdk = sdk.ok_or_else(|| "--sdk is required".to_string())?;
    generate_dart_bindings(&sdk, check)
}

fn generate_dart_bindings(sdk: &Path, check: bool) -> Result<(), String> {
    let workspace = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .ok_or_else(|| "xtask must live under the workspace crates directory".to_string())?;
    let dart_vm = workspace.join("crates/dart-vm");
    let expected_version = fs::read_to_string(dart_vm.join("DART_SDK_VERSION"))
        .map_err(|error| format!("read pinned Dart SDK version: {error}"))?;
    let actual_version = fs::read_to_string(sdk.join("version"))
        .map_err(|error| format!("read {}: {error}", sdk.join("version").display()))?;
    let expected_version = expected_version.trim();
    let actual_version = actual_version.trim();
    if actual_version != expected_version {
        return Err(format!(
            "Dart SDK {actual_version} does not match pinned version {expected_version}"
        ));
    }
    let header = sdk.join("include/dart_api.h");
    if !header.is_file() {
        return Err(format!("missing {}", header.display()));
    }

    let mut wrapper = String::from("#include <dart_api.h>\n");
    for symbol in SYMBOLS {
        wrapper.push_str(&format!("typedef __typeof__({symbol}) *Oche_{symbol};\n"));
    }
    let bindings = bindgen::Builder::default()
        .header_contents("oche_dart_api.h", &wrapper)
        .clang_arg(format!("-I{}", sdk.join("include").display()))
        .allowlist_type("Oche_Dart_.*")
        .allowlist_recursively(true)
        .derive_debug(true)
        .derive_default(true)
        .generate_comments(false)
        .layout_tests(false)
        .formatter(bindgen::Formatter::Rustfmt)
        .generate()
        .map_err(|error| format!("generate bindings from {}: {error}", header.display()))?;
    let generated = format!(
        "// Generated by `cargo run -p xtask -- dart-bindings`; do not edit.\n\
         // Dart SDK: {actual_version}\n\n{}",
        bindings
    );
    let output = dart_vm.join("src/generated/dart_api.rs");
    if check {
        let current = fs::read_to_string(&output)
            .map_err(|error| format!("read {}: {error}", output.display()))?;
        if current != generated {
            return Err(format!(
                "{} is stale; regenerate it with Dart SDK {actual_version}",
                output.display()
            ));
        }
    } else {
        fs::create_dir_all(output.parent().unwrap())
            .map_err(|error| format!("create generated binding directory: {error}"))?;
        fs::write(&output, generated)
            .map_err(|error| format!("write {}: {error}", output.display()))?;
        println!(
            "Generated {} for Dart SDK {actual_version}",
            output.display()
        );
    }
    Ok(())
}
