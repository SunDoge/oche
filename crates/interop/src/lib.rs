//! Generate narrow Oche declaration files from Dart source.

use std::fmt::Write;

use snafu::Snafu;

#[derive(Debug, PartialEq, Snafu)]
pub enum Error {
    #[snafu(display("No supported public top-level Dart functions were found"))]
    NoSupportedFunctions,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Report {
    pub definitions: String,
    pub exported: Vec<String>,
    pub skipped: usize,
}

pub fn generate(source: &str, uri: &str) -> Result<Report, Error> {
    let mut functions = Vec::new();
    let mut skipped = 0;
    let mut brace_depth = 0_i32;
    for line in source.lines() {
        let declaration = line.split("//").next().unwrap_or("").trim();
        if brace_depth == 0 && declaration.contains('(') {
            match parse_function(declaration) {
                Some(function) => functions.push(function),
                None if looks_like_public_function(declaration) => skipped += 1,
                None => {}
            }
        }
        brace_depth += declaration.matches('{').count() as i32;
        brace_depth -= declaration.matches('}').count() as i32;
    }
    if functions.is_empty() {
        return Err(Error::NoSupportedFunctions);
    }

    let mut definitions = String::from("// Generated by Oche bindgen. Do not edit.\n");
    definitions.push_str(
        "// Supported Dart surface: top-level int, double, bool, String, and Future functions.\n\n",
    );
    definitions.push_str("dart ");
    write_string(&mut definitions, uri);
    definitions.push_str(" {\n");
    for function in &functions {
        write!(definitions, "  fn {}(", function.name).unwrap();
        for (index, (name, ty)) in function.parameters.iter().enumerate() {
            if index != 0 {
                definitions.push_str(", ");
            }
            write!(definitions, "{name}: {ty}").unwrap();
        }
        writeln!(definitions, ") -> {}", function.result).unwrap();
    }
    definitions.push_str("}\n");
    Ok(Report {
        exported: functions
            .iter()
            .map(|function| function.name.clone())
            .collect(),
        definitions,
        skipped,
    })
}

#[derive(Debug)]
struct Function {
    name: String,
    parameters: Vec<(String, String)>,
    result: String,
}

fn looks_like_public_function(line: &str) -> bool {
    let Some((prefix, _)) = line.split_once('(') else {
        return false;
    };
    let words = prefix.split_whitespace().collect::<Vec<_>>();
    words.len() == 2 && !words[1].starts_with('_')
}

fn parse_function(line: &str) -> Option<Function> {
    let (prefix, remainder) = line.split_once('(')?;
    let (parameters, suffix) = remainder.split_once(')')?;
    let words = prefix.split_whitespace().collect::<Vec<_>>();
    if words.len() != 2 || words[1].starts_with('_') || !valid_name(words[1]) {
        return None;
    }
    let result = map_type(words[0])?;
    let suffix = suffix.trim();
    if !(suffix.starts_with("=>")
        || suffix.starts_with('{')
        || suffix.starts_with("async =>")
        || suffix.starts_with("async {"))
    {
        return None;
    }
    let mut parsed_parameters = Vec::new();
    if !parameters.trim().is_empty() {
        for parameter in parameters.split(',') {
            let words = parameter.split_whitespace().collect::<Vec<_>>();
            if words.len() != 2 || !valid_name(words[1]) {
                return None;
            }
            parsed_parameters.push((words[1].into(), map_type(words[0])?));
        }
    }
    Some(Function {
        name: words[1].into(),
        parameters: parsed_parameters,
        result,
    })
}

fn map_type(value: &str) -> Option<String> {
    match value {
        "int" => Some("Int".into()),
        "double" => Some("Float".into()),
        "bool" => Some("Bool".into()),
        "String" => Some("String".into()),
        _ => value
            .strip_prefix("Future<")
            .and_then(|inner| inner.strip_suffix('>'))
            .and_then(map_type)
            .map(|inner| format!("Future<{inner}>")),
    }
}

fn valid_name(value: &str) -> bool {
    !matches!(
        value,
        "fn" | "async"
            | "await"
            | "struct"
            | "enum"
            | "comptime"
            | "import"
            | "dart"
            | "let"
            | "try"
            | "match"
            | "true"
            | "false"
    ) && value.bytes().enumerate().all(|(index, byte)| {
        byte == b'_' || byte.is_ascii_alphabetic() || index > 0 && byte.is_ascii_digit()
    })
}

fn write_string(output: &mut String, value: &str) {
    output.push('"');
    for character in value.chars() {
        match character {
            '"' => output.push_str("\\\""),
            '\\' => output.push_str("\\\\"),
            '\n' => output.push_str("\\n"),
            _ => output.push(character),
        }
    }
    output.push('"');
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn emits_supported_top_level_functions() {
        let report = generate(
            "String greet(String name) => 'hello $name';\nint add(int a, int b) { return a + b; }\nFuture<String> later(String value) async => value;\ndouble ratio(int a) => 1.0;\n",
            "file:///tmp/tools.dart",
        )
        .unwrap();
        assert_eq!(report.exported, ["greet", "add", "later", "ratio"]);
        assert_eq!(report.skipped, 0);
        assert!(report.definitions.contains("fn add(a: Int, b: Int) -> Int"));
        assert!(
            report
                .definitions
                .contains("fn later(value: String) -> Future<String>")
        );
        assert!(report.definitions.contains("fn ratio(a: Int) -> Float"));
    }
}
